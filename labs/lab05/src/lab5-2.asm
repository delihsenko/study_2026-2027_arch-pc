; --------------------------------------------------------------------
; Программа вывода сообщения на экран и ввода строки с клавиатуры
; --------------------------------------------------------------------

%include 'in_out.asm'                   ; подключение внешнего файла

SECTION .data                           ; секция инициализированных данных
msg:    DB 'Введите строку: ', 0h       ; выводимое сообщение

SECTION .bss                            ; секция неинициализированных данных
buf1:   RESB 80                         ; буфер размером 80 байт

SECTION .text                           ; код программы
GLOBAL _start                           ; точка входа в программу

_start:
    mov     eax, msg                    ; адрес выводимого сообщения в EAX
    call    sprint                    ; печать сообщения с переводом строки

    mov     ecx, buf1                   ; адрес буфера в ECX
    mov     edx, 80                     ; длина вводимой строки в EDX
    call    sread                       ; ввод строки с клавиатуры

    call    quit                        ; завершение программы